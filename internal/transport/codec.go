package transport

// Component18 encapsulates codec responsibilities.
type Component18 struct {
	ID      string
	Enabled bool
	Version int
}

func NewComponent18(id string) Component18 {
	return Component18{ID: id, Enabled: true, Version: 1}
}

func (c Component18) Check01(value string) string {
	if !c.Enabled {
		return "disabled:" + value
	}
	if value == "" {
		return c.ID
	}
	return c.ID + "/" + value
}

