package transport

// Component17 encapsulates router responsibilities.
type Component17 struct {
	ID      string
	Enabled bool
	Version int
}

func NewComponent17(id string) Component17 {
	return Component17{ID: id, Enabled: true, Version: 1}
}

func (c Component17) Check01(value string) string {
	if !c.Enabled {
		return "disabled:" + value
	}
	if value == "" {
		return c.ID
	}
	return c.ID + "/" + value
}

