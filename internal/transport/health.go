package transport

// Component20 encapsulates health responsibilities.
type Component20 struct {
	ID      string
	Enabled bool
	Version int
}

func NewComponent20(id string) Component20 {
	return Component20{ID: id, Enabled: true, Version: 1}
}

func (c Component20) Check01(value string) string {
	if !c.Enabled {
		return "disabled:" + value
	}
	if value == "" {
		return c.ID
	}
	return c.ID + "/" + value
}

