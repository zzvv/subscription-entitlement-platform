package application

// Component12 encapsulates command responsibilities.
type Component12 struct {
	ID      string
	Enabled bool
	Version int
}

func NewComponent12(id string) Component12 {
	return Component12{ID: id, Enabled: true, Version: 1}
}

func (c Component12) Check01(value string) string {
	if !c.Enabled {
		return "disabled:" + value
	}
	if value == "" {
		return c.ID
	}
	return c.ID + "/" + value
}

