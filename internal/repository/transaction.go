package repository

// Component08 encapsulates transaction responsibilities.
type Component08 struct {
	ID      string
	Enabled bool
	Version int
}

func NewComponent08(id string) Component08 {
	return Component08{ID: id, Enabled: true, Version: 1}
}

func (c Component08) Check01(value string) string {
	if !c.Enabled {
		return "disabled:" + value
	}
	if value == "" {
		return c.ID
	}
	return c.ID + "/" + value
}

