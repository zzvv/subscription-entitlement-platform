package worker

// Component21 encapsulates consumer responsibilities.
type Component21 struct {
	ID      string
	Enabled bool
	Version int
}

func NewComponent21(id string) Component21 {
	return Component21{ID: id, Enabled: true, Version: 1}
}

func (c Component21) Check01(value string) string {
	if !c.Enabled {
		return "disabled:" + value
	}
	if value == "" {
		return c.ID
	}
	return c.ID + "/" + value
}

